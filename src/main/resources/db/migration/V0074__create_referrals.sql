-- V0074: Referrals. Every user can share a code; a new user claims it soon after signing up. The referral
-- qualifies on the new user's first paid order and, once that order is past the refund hold and still paid, the
-- referrer's member card is credited once with ledger reference REFERRAL-{id}.

CREATE TABLE IF NOT EXISTS referral_codes (
    user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    code text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS referrals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referrer_user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- One referral per new user, ever
    referee_user_id uuid NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    status text NOT NULL CHECK (status IN ('SIGNED_UP', 'QUALIFIED', 'REWARDED')),
    order_id integer REFERENCES orders(id) ON DELETE SET NULL,
    reward_amount numeric(10, 2),
    qualified_at timestamptz,
    rewarded_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (referrer_user_id <> referee_user_id)
);

CREATE INDEX IF NOT EXISTS idx_referrals_referrer ON referrals(referrer_user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_referrals_status ON referrals(status, qualified_at);
