-- V0073: Anonymous catalog events for the admin funnel (view, add to cart, checkout start). Visitors are kept only
-- as a salted hash, never an IP address or account id. Old rows are pruned by CatalogEventPruneJob.

CREATE TABLE IF NOT EXISTS catalog_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    event text NOT NULL CHECK (event IN ('VIEW', 'ADD_TO_CART', 'CHECKOUT_START')),
    visitor_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_catalog_events_time ON catalog_events(created_at);
CREATE INDEX IF NOT EXISTS idx_catalog_events_course ON catalog_events(course_id, event, created_at);
CREATE INDEX IF NOT EXISTS idx_catalog_events_dedupe ON catalog_events(visitor_hash, course_id, event, created_at DESC);
