-- V0039: Questions and answers on a lesson. Names are copied on write, so a thread still reads
-- correctly after an account is deleted.

CREATE TABLE IF NOT EXISTS lesson_questions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    author_id uuid REFERENCES users(id) ON DELETE SET NULL,
    author_name text NOT NULL,
    body text NOT NULL,
    resolved boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_lesson_questions_lesson ON lesson_questions (lesson_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_lesson_questions_open ON lesson_questions (created_at DESC) WHERE NOT resolved;

CREATE TABLE IF NOT EXISTS lesson_answers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id integer NOT NULL REFERENCES lesson_questions(id) ON DELETE CASCADE,
    author_id uuid REFERENCES users(id) ON DELETE SET NULL,
    author_name text NOT NULL,
    from_staff boolean NOT NULL DEFAULT false,
    body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_lesson_answers_question ON lesson_answers (question_id, created_at);
