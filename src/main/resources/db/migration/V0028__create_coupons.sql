-- V0028: Discount codes. Redemptions are derived from orders, so cancelling or refunding frees a use.

CREATE TABLE IF NOT EXISTS coupons (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    discount_type text NOT NULL CHECK (discount_type IN ('PERCENT', 'FIXED')),
    discount_value numeric(10, 2) NOT NULL CHECK (discount_value > 0),
    -- Null applies to every course
    course_id integer REFERENCES courses(id) ON DELETE CASCADE,
    max_redemptions integer CHECK (max_redemptions > 0),
    starts_at timestamptz,
    expires_at timestamptz,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (discount_type <> 'PERCENT' OR discount_value <= 100)
);

ALTER TABLE orders ADD COLUMN IF NOT EXISTS coupon_id integer REFERENCES coupons(id);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS list_amount numeric(10, 2);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_amount numeric(10, 2) NOT NULL DEFAULT 0;

UPDATE orders SET list_amount = amount WHERE list_amount IS NULL;
ALTER TABLE orders ALTER COLUMN list_amount SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_orders_coupon ON orders (coupon_id, status) WHERE coupon_id IS NOT NULL;
