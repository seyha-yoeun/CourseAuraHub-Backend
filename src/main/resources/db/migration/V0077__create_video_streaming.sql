-- V0077: Adaptive streaming for video lessons. Uploaded MP4/WebM files are transcoded to HLS in the background;
-- the playlist and segments stay private and are signed per request for learners who can watch the lesson.
-- Captions are WebVTT files, one per language.

ALTER TABLE lessons ADD COLUMN IF NOT EXISTS video_status text
    CHECK (video_status IS NULL OR video_status IN ('PROCESSING', 'READY', 'FAILED'));
ALTER TABLE lessons ADD COLUMN IF NOT EXISTS hls_manifest_ref text;
-- The content_url the current stream was made from; a different upload means a new transcode
ALTER TABLE lessons ADD COLUMN IF NOT EXISTS video_source_ref text;
ALTER TABLE lessons ADD COLUMN IF NOT EXISTS duration_seconds integer;

CREATE TABLE IF NOT EXISTS video_transcode_jobs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    source_ref text NOT NULL,
    status text NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    attempts integer NOT NULL DEFAULT 0,
    error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_video_transcode_jobs_status ON video_transcode_jobs(status, created_at);
CREATE UNIQUE INDEX IF NOT EXISTS uq_video_transcode_jobs_open ON video_transcode_jobs(lesson_id, source_ref)
    WHERE status IN ('QUEUED', 'RUNNING');

CREATE TABLE IF NOT EXISTS lesson_captions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    language text NOT NULL,
    label text NOT NULL,
    file_ref text NOT NULL,
    created_by uuid REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (lesson_id, language)
);
