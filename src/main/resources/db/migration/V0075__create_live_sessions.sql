-- V0075: Scheduled live classes for a course. Learners see them without the meeting link; joining records
-- attendance and returns it. A personal calendar token lets calendar apps read a learner's sessions as ICS.

CREATE TABLE IF NOT EXISTS live_sessions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title text NOT NULL,
    description text,
    starts_at timestamptz NOT NULL,
    duration_minutes integer NOT NULL CHECK (duration_minutes BETWEEN 5 AND 600),
    meeting_url text NOT NULL,
    recording_lesson_id integer REFERENCES lessons(id) ON DELETE SET NULL,
    cancelled boolean NOT NULL DEFAULT false,
    reminded_hour boolean NOT NULL DEFAULT false,
    reminded_soon boolean NOT NULL DEFAULT false,
    created_by uuid REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_live_sessions_course ON live_sessions(course_id, starts_at);
CREATE INDEX IF NOT EXISTS idx_live_sessions_upcoming ON live_sessions(starts_at) WHERE NOT cancelled;

CREATE TABLE IF NOT EXISTS live_attendance (
    session_id integer NOT NULL REFERENCES live_sessions(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    joined_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (session_id, student_id)
);

-- Only a keyed hash of the token is stored; rotating it replaces the row
CREATE TABLE IF NOT EXISTS calendar_tokens (
    user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    token_hash text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now()
);
