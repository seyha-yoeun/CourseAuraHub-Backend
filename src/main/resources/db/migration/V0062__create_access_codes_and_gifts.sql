-- V0062: Redeemable access codes. Admins issue batches of them; a learner buying a course as a gift gets one made
-- for the recipient once the order is paid. Codes are stored as HMAC hashes, like other secrets.

ALTER TABLE orders ADD COLUMN IF NOT EXISTS gift boolean NOT NULL DEFAULT false;

-- A buyer may have their own checkout and gift checkouts for the same course open at once
DROP INDEX IF EXISTS uq_orders_pending_student_course;
CREATE UNIQUE INDEX IF NOT EXISTS uq_orders_pending_student_course
    ON orders (student_id, course_id) WHERE status = 'PENDING' AND NOT gift;

CREATE TABLE IF NOT EXISTS access_codes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash text NOT NULL UNIQUE,
    code_hint text NOT NULL,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    batch text,
    max_uses integer NOT NULL CHECK (max_uses BETWEEN 1 AND 100000),
    uses integer NOT NULL DEFAULT 0 CHECK (uses >= 0),
    expires_at timestamptz,
    revoked boolean NOT NULL DEFAULT false,
    created_by uuid REFERENCES users(id) ON DELETE SET NULL,
    -- Gift codes: the paid order, who bought it, for whom and their message
    gift_order_id integer UNIQUE REFERENCES orders(id) ON DELETE SET NULL,
    purchaser_student_id integer REFERENCES students(id) ON DELETE SET NULL,
    recipient_email text,
    message text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_access_codes_batch ON access_codes(batch);
CREATE INDEX IF NOT EXISTS idx_access_codes_purchaser ON access_codes(purchaser_student_id);

CREATE TABLE IF NOT EXISTS access_code_redemptions (
    code_id integer NOT NULL REFERENCES access_codes(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    redeemed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (code_id, student_id)
);
