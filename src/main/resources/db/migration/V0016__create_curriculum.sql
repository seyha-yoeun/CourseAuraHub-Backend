-- V0016: Course curriculum (sections, lessons) and per-learner lesson progress.

CREATE TABLE IF NOT EXISTS course_sections (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title text NOT NULL,
    position integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_course_sections_course_id ON course_sections(course_id, position);

CREATE TABLE IF NOT EXISTS lessons (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id integer NOT NULL REFERENCES course_sections(id) ON DELETE CASCADE,
    title text NOT NULL,
    type text NOT NULL CHECK (type IN ('VIDEO', 'ARTICLE', 'QUIZ')),
    duration_minutes integer NOT NULL DEFAULT 0 CHECK (duration_minutes >= 0),
    content_url text,
    is_preview boolean NOT NULL DEFAULT false,
    position integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_lessons_section_id ON lessons(section_id, position);

CREATE TABLE IF NOT EXISTS lesson_progress (
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    completed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (student_id, lesson_id)
);

CREATE INDEX IF NOT EXISTS idx_lesson_progress_lesson_id ON lesson_progress(lesson_id);
