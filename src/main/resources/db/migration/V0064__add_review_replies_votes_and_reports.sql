-- V0064: Instructors reply to reviews, learners mark reviews helpful, and anyone signed in can report a review,
-- question or answer. Hidden content disappears from public lists and from the course rating.

ALTER TABLE course_reviews ADD COLUMN IF NOT EXISTS hidden boolean NOT NULL DEFAULT false;
ALTER TABLE course_reviews ADD COLUMN IF NOT EXISTS helpful_count integer NOT NULL DEFAULT 0;
ALTER TABLE course_reviews ADD COLUMN IF NOT EXISTS reply text;
ALTER TABLE course_reviews ADD COLUMN IF NOT EXISTS reply_author_id uuid REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE course_reviews ADD COLUMN IF NOT EXISTS reply_author_name text;
ALTER TABLE course_reviews ADD COLUMN IF NOT EXISTS replied_at timestamptz;

ALTER TABLE lesson_questions ADD COLUMN IF NOT EXISTS hidden boolean NOT NULL DEFAULT false;
ALTER TABLE lesson_answers ADD COLUMN IF NOT EXISTS hidden boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS review_votes (
    review_id integer NOT NULL REFERENCES course_reviews(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (review_id, student_id)
);

CREATE TABLE IF NOT EXISTS content_reports (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type text NOT NULL CHECK (target_type IN ('REVIEW', 'QUESTION', 'ANSWER')),
    target_id integer NOT NULL,
    reporter_id uuid REFERENCES users(id) ON DELETE SET NULL,
    reason text NOT NULL,
    status text NOT NULL CHECK (status IN ('OPEN', 'HIDDEN', 'DISMISSED')),
    resolved_by uuid REFERENCES users(id) ON DELETE SET NULL,
    resolved_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (target_type, target_id, reporter_id)
);

CREATE INDEX IF NOT EXISTS idx_content_reports_open ON content_reports(status, created_at);
CREATE INDEX IF NOT EXISTS idx_course_reviews_helpful ON course_reviews(course_id, helpful_count DESC);
