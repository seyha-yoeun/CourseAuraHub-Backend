-- V0026: Course completion certificates. Issued once, the first time a learner completes a course,
-- and kept even if the course's lesson set later changes.

CREATE TABLE IF NOT EXISTS course_certificates (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_number text NOT NULL UNIQUE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    issued_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (student_id, course_id)
);

CREATE INDEX IF NOT EXISTS idx_course_certificates_course_id ON course_certificates(course_id);

-- Backfill completions recorded before certificates existed (64 random bits per number)
INSERT INTO course_certificates (certificate_number, student_id, course_id)
SELECT 'CAH-' || substr(code, 1, 4) || '-' || substr(code, 5, 4) || '-' || substr(code, 9, 4) || '-' || substr(code, 13, 4),
       student_id,
       course_id
FROM (
    SELECT sc.student_id, sc.course_id, upper(substr(md5(gen_random_uuid()::text), 1, 16)) AS code
    FROM student_courses sc
    WHERE sc.completed
) completed
ON CONFLICT DO NOTHING;
