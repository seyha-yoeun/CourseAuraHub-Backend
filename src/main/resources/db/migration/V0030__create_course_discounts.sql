-- V0030: Scheduled sale prices. courses.price stays the regular price; the sale is applied when it is read.

CREATE TABLE IF NOT EXISTS course_discounts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    discount_type text NOT NULL CHECK (discount_type IN ('PERCENT', 'FIXED')),
    discount_value numeric(10, 2) NOT NULL CHECK (discount_value > 0),
    starts_at timestamptz NOT NULL,
    -- Null runs until an admin ends it
    ends_at timestamptz,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (discount_type <> 'PERCENT' OR discount_value <= 100),
    CHECK (ends_at IS NULL OR ends_at > starts_at)
);

CREATE INDEX IF NOT EXISTS idx_course_discounts_course ON course_discounts (course_id) WHERE active;
