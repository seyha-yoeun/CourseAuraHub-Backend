-- V0069: Instructors earn a share of each paid order for a course they own. Earnings wait out the refund window,
-- then become available and are paid out on request after an admin approves. Admin-owned courses earn nothing.

-- The instructor's share for one course; courses without a row use app.payouts.instructor-share-percent
CREATE TABLE IF NOT EXISTS course_revenue_shares (
    course_id integer PRIMARY KEY REFERENCES courses(id) ON DELETE CASCADE,
    instructor_percent numeric(5, 2) NOT NULL CHECK (instructor_percent >= 0 AND instructor_percent <= 100),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS payout_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instructor_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    amount numeric(10, 2) NOT NULL CHECK (amount > 0),
    currency text NOT NULL,
    method text NOT NULL,
    account_details text NOT NULL,
    note text,
    status text NOT NULL CHECK (status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'PAID')),
    decision_note text,
    payment_reference text,
    reviewed_by uuid REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    paid_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One open payout per instructor, so two requests can never claim the same earnings
CREATE UNIQUE INDEX IF NOT EXISTS uq_payout_requests_open ON payout_requests(instructor_id)
    WHERE status IN ('REQUESTED', 'APPROVED');
CREATE INDEX IF NOT EXISTS idx_payout_requests_status ON payout_requests(status, created_at);

-- A SALE row per paid order. A refund after the money was claimed adds a negative REFUND row instead of
-- reversing the sale, so it comes off the next payout.
CREATE TABLE IF NOT EXISTS instructor_earnings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instructor_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    type text NOT NULL CHECK (type IN ('SALE', 'REFUND')),
    gross numeric(10, 2) NOT NULL,
    platform_fee numeric(10, 2) NOT NULL,
    net numeric(10, 2) NOT NULL,
    share_percent numeric(5, 2) NOT NULL,
    currency text NOT NULL,
    status text NOT NULL CHECK (status IN ('PENDING', 'AVAILABLE', 'PAID', 'REVERSED')),
    available_at timestamptz NOT NULL,
    payout_id integer REFERENCES payout_requests(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_instructor_earnings_order_type ON instructor_earnings(order_id, type);
CREATE INDEX IF NOT EXISTS idx_instructor_earnings_instructor ON instructor_earnings(instructor_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_instructor_earnings_pending ON instructor_earnings(available_at) WHERE status = 'PENDING';
