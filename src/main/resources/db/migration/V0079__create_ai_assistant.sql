-- V0079: An AI study assistant that answers from a lesson's own study text. Staff paste the text a lesson should be
-- answered from (an article, a transcript); conversations are kept per learner and lesson; usage is counted per day
-- for the daily limit. Learner names and emails are never sent to the model.

CREATE TABLE IF NOT EXISTS lesson_ai_sources (
    lesson_id integer PRIMARY KEY REFERENCES lessons(id) ON DELETE CASCADE,
    body text NOT NULL,
    updated_by uuid REFERENCES users(id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lesson_ai_summaries (
    lesson_id integer PRIMARY KEY REFERENCES lessons(id) ON DELETE CASCADE,
    -- SHA-256 of what the summary was made from, so a changed lesson gets a new one
    source_hash text NOT NULL,
    summary text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS assistant_conversations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_assistant_conversations_learner ON assistant_conversations(student_id, lesson_id, created_at DESC);

CREATE TABLE IF NOT EXISTS assistant_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint NOT NULL REFERENCES assistant_conversations(id) ON DELETE CASCADE,
    role text NOT NULL CHECK (role IN ('USER', 'ASSISTANT')),
    content text NOT NULL,
    input_tokens integer,
    output_tokens integer,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_assistant_messages_conversation ON assistant_messages(conversation_id, id);

CREATE TABLE IF NOT EXISTS assistant_usage (
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    usage_date date NOT NULL,
    requests integer NOT NULL DEFAULT 0,
    tokens bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (student_id, usage_date)
);
