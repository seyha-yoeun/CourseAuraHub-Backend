-- V0043: One assignment per lesson, and one submission per learner that is replaced on resubmitting.

CREATE TABLE IF NOT EXISTS assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id integer NOT NULL UNIQUE REFERENCES lessons(id) ON DELETE CASCADE,
    instructions text NOT NULL,
    pass_score integer NOT NULL DEFAULT 50 CHECK (pass_score BETWEEN 0 AND 100),
    required boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS assignment_submissions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    file_url text,
    file_name text,
    comment text,
    status text NOT NULL,
    score integer CHECK (score BETWEEN 0 AND 100),
    feedback text,
    graded_by uuid REFERENCES users(id) ON DELETE SET NULL,
    graded_at timestamptz,
    submitted_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (assignment_id, student_id),
    CHECK (file_url IS NOT NULL OR comment IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_assignment_submissions_status ON assignment_submissions (status, submitted_at);
