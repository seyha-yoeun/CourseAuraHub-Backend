-- V0027: Course purchases. Orders outlive the enrollment they create, so refunds stay on record.

CREATE TABLE IF NOT EXISTS orders (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number       text NOT NULL UNIQUE,
    student_id         integer NOT NULL REFERENCES students (id),
    course_id          integer NOT NULL REFERENCES courses (id),
    amount             numeric(10, 2) NOT NULL CHECK (amount >= 0),
    currency           text NOT NULL,
    status             text NOT NULL CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'CANCELLED', 'REFUNDED')),
    provider           text,
    provider_reference text,
    checkout_url       text,
    created_at         timestamptz NOT NULL,
    paid_at            timestamptz,
    refunded_at        timestamptz
);

CREATE INDEX IF NOT EXISTS idx_orders_student ON orders (student_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders (status, created_at DESC);

-- A learner has at most one open checkout per course
CREATE UNIQUE INDEX IF NOT EXISTS uq_orders_pending_student_course
    ON orders (student_id, course_id) WHERE status = 'PENDING';
