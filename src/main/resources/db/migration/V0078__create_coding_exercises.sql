-- V0078: CODE lessons with a coding exercise. Learners' code runs in an external sandbox (Judge0) against the
-- exercise's tests; passing completes the lesson. Hidden tests never reach learners.

ALTER TABLE lessons DROP CONSTRAINT IF EXISTS lessons_type_check;
ALTER TABLE lessons ADD CONSTRAINT lessons_type_check CHECK (type IN ('VIDEO', 'ARTICLE', 'QUIZ', 'CODE'));

CREATE TABLE IF NOT EXISTS code_exercises (
    lesson_id integer PRIMARY KEY REFERENCES lessons(id) ON DELETE CASCADE,
    language text NOT NULL,
    instructions text,
    starter_code text NOT NULL DEFAULT '',
    -- Visible to learners: [{"input": "...", "expectedOutput": "..."}]
    examples jsonb NOT NULL DEFAULT '[]'::jsonb,
    -- Hidden from learners, same shape
    tests jsonb NOT NULL DEFAULT '[]'::jsonb,
    time_limit_seconds numeric(4, 1) NOT NULL DEFAULT 2.0 CHECK (time_limit_seconds > 0 AND time_limit_seconds <= 15),
    memory_limit_mb integer NOT NULL DEFAULT 128 CHECK (memory_limit_mb BETWEEN 16 AND 512),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS code_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    language text NOT NULL,
    code text NOT NULL,
    passed boolean NOT NULL,
    passed_tests integer NOT NULL,
    total_tests integer NOT NULL,
    -- What the learner was shown: verdict and messages, never hidden inputs or outputs
    result jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_code_submissions_learner ON code_submissions(student_id, lesson_id, created_at DESC);
