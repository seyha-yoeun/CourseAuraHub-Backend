-- V0071: Browser push subscriptions (Web Push with VAPID). A user can subscribe several browsers; each endpoint
-- belongs to one user. Push is on for every notification type unless the user mutes it.

CREATE TABLE IF NOT EXISTS push_subscriptions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    endpoint text NOT NULL UNIQUE,
    p256dh text NOT NULL,
    auth text NOT NULL,
    user_agent text,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_success_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_push_subscriptions_user ON push_subscriptions(user_id);

CREATE TABLE IF NOT EXISTS push_muted_types (
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type text NOT NULL,
    PRIMARY KEY (user_id, type)
);
