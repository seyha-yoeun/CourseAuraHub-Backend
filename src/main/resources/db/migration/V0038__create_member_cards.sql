-- V0038: Member cards. Learners apply, admins approve, and a stored balance can pay for courses.
-- The balance is only ever changed together with a row in member_card_transactions.

CREATE TABLE IF NOT EXISTS member_card_applications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id),
    full_name text NOT NULL,
    phone text NOT NULL,
    date_of_birth date NOT NULL,
    address text NOT NULL,
    status text NOT NULL,
    review_note text,
    reviewed_by uuid REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One application under review per learner
CREATE UNIQUE INDEX IF NOT EXISTS uq_member_card_applications_pending
    ON member_card_applications (student_id) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_member_card_applications_status
    ON member_card_applications (status, created_at DESC);

CREATE TABLE IF NOT EXISTS member_cards (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_number text NOT NULL UNIQUE,
    student_id integer NOT NULL UNIQUE REFERENCES students(id),
    holder_name text NOT NULL,
    balance numeric(12, 2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    status text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS member_card_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id integer NOT NULL REFERENCES member_cards(id),
    type text NOT NULL,
    amount numeric(12, 2) NOT NULL CHECK (amount > 0),
    balance_after numeric(12, 2) NOT NULL CHECK (balance_after >= 0),
    reference text,
    idempotency_key text,
    note text,
    performed_by uuid REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_member_card_transactions_card
    ON member_card_transactions (card_id, created_at DESC, id DESC);
-- The database refuses a second charge or refund for the same order, and a replayed admin adjustment
CREATE UNIQUE INDEX IF NOT EXISTS uq_member_card_transactions_reference
    ON member_card_transactions (type, reference) WHERE reference IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_member_card_transactions_idempotency
    ON member_card_transactions (card_id, idempotency_key) WHERE idempotency_key IS NOT NULL;
