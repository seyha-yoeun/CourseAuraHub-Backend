-- V0035: Graded quizzes. A QUIZ lesson with questions must be passed to complete it. QUIZ lessons
-- without questions keep working as before, so existing courses and certificates are unaffected.

ALTER TABLE lessons ADD COLUMN IF NOT EXISTS quiz_pass_percent integer NOT NULL DEFAULT 70
    CHECK (quiz_pass_percent BETWEEN 1 AND 100);

CREATE TABLE IF NOT EXISTS quiz_questions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    position integer NOT NULL,
    prompt text NOT NULL,
    explanation text
);

CREATE INDEX IF NOT EXISTS idx_quiz_questions_lesson ON quiz_questions(lesson_id, position);

CREATE TABLE IF NOT EXISTS quiz_options (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id integer NOT NULL REFERENCES quiz_questions(id) ON DELETE CASCADE,
    position integer NOT NULL,
    text text NOT NULL,
    correct boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_quiz_options_question ON quiz_options(question_id, position);

CREATE TABLE IF NOT EXISTS quiz_attempts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    correct_count integer NOT NULL,
    total_count integer NOT NULL,
    score_percent integer NOT NULL,
    passed boolean NOT NULL,
    submitted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_quiz_attempts_student_lesson ON quiz_attempts(student_id, lesson_id, submitted_at DESC);
