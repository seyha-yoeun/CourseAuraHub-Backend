-- V0040: A learner's private notes. A note with a video position and no text is a bookmark.

CREATE TABLE IF NOT EXISTS lesson_notes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    lesson_id integer NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    body text,
    position_seconds integer CHECK (position_seconds >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (body IS NOT NULL OR position_seconds IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_lesson_notes_student_lesson ON lesson_notes (student_id, lesson_id, created_at DESC);
