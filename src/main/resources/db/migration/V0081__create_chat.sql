-- V0081: Real-time chat. DIRECT (two people who share a course), COURSE (one official channel per course),
-- GROUP (private, user-created, inside one course) and SUPPORT (a user and the admin team).
-- Access is decided live from enrollments and course ownership; these tables hold membership, read state and messages.

CREATE TABLE IF NOT EXISTS chat_conversations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type text NOT NULL CHECK (type IN ('DIRECT', 'COURSE', 'GROUP', 'SUPPORT')),
    course_id integer REFERENCES courses(id) ON DELETE CASCADE,
    -- "<smaller uuid>:<larger uuid>", so a pair of people has one direct conversation
    direct_key text,
    title text,
    description text,
    owner_id uuid REFERENCES users(id) ON DELETE SET NULL,
    allow_member_invites boolean NOT NULL DEFAULT false,
    status text NOT NULL CHECK (status IN ('ACTIVE', 'ARCHIVED', 'OPEN', 'CLOSED')),
    created_by uuid REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_message_id integer,
    last_activity_at timestamptz NOT NULL DEFAULT now(),
    -- Optimistic lock for group settings
    version integer NOT NULL DEFAULT 0,
    CONSTRAINT chk_chat_conversation_shape CHECK (
        (type = 'DIRECT' AND direct_key IS NOT NULL AND course_id IS NULL AND owner_id IS NULL)
        OR (type = 'COURSE' AND course_id IS NOT NULL AND direct_key IS NULL AND owner_id IS NULL)
        OR (type = 'GROUP' AND course_id IS NOT NULL AND direct_key IS NULL AND title IS NOT NULL)
        OR (type = 'SUPPORT' AND course_id IS NULL AND direct_key IS NULL AND owner_id IS NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_chat_course_channel ON chat_conversations(course_id) WHERE type = 'COURSE';
CREATE UNIQUE INDEX IF NOT EXISTS uq_chat_direct_pair ON chat_conversations(direct_key) WHERE type = 'DIRECT';
CREATE UNIQUE INDEX IF NOT EXISTS uq_chat_open_support ON chat_conversations(created_by)
    WHERE type = 'SUPPORT' AND status = 'OPEN';
CREATE INDEX IF NOT EXISTS idx_chat_conversations_course ON chat_conversations(course_id, type);
CREATE INDEX IF NOT EXISTS idx_chat_conversations_support ON chat_conversations(status, last_activity_at)
    WHERE type = 'SUPPORT';

CREATE TABLE IF NOT EXISTS chat_participants (
    conversation_id integer NOT NULL REFERENCES chat_conversations(id) ON DELETE CASCADE,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role text NOT NULL CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER')),
    joined_at timestamptz NOT NULL DEFAULT now(),
    left_at timestamptz,
    left_reason text CHECK (left_reason IN ('LEFT', 'REMOVED', 'INELIGIBLE')),
    removed_by uuid REFERENCES users(id) ON DELETE SET NULL,
    last_read_message_id integer NOT NULL DEFAULT 0,
    last_delivered_message_id integer NOT NULL DEFAULT 0,
    muted boolean NOT NULL DEFAULT false,
    hidden_at timestamptz,
    PRIMARY KEY (conversation_id, user_id)
);

-- A group always has at most one active owner
CREATE UNIQUE INDEX IF NOT EXISTS uq_chat_one_owner ON chat_participants(conversation_id)
    WHERE role = 'OWNER' AND left_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_chat_participants_user ON chat_participants(user_id) WHERE left_at IS NULL;

CREATE TABLE IF NOT EXISTS chat_messages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id integer NOT NULL REFERENCES chat_conversations(id) ON DELETE CASCADE,
    -- Null for system lines ("Jane L. joined")
    sender_id uuid REFERENCES users(id) ON DELETE SET NULL,
    -- The sender's own id for this send, so a retried send never stores the message twice
    client_message_id uuid,
    kind text NOT NULL CHECK (kind IN ('TEXT', 'SYSTEM')),
    body text,
    created_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    hidden_at timestamptz,
    hidden_by uuid REFERENCES users(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_chat_message_client_id ON chat_messages(sender_id, client_message_id)
    WHERE client_message_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_chat_messages_conversation ON chat_messages(conversation_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_chat_messages_sender ON chat_messages(sender_id);

ALTER TABLE chat_conversations DROP CONSTRAINT IF EXISTS fk_chat_conversation_last_message;
ALTER TABLE chat_conversations ADD CONSTRAINT fk_chat_conversation_last_message
    FOREIGN KEY (last_message_id) REFERENCES chat_messages(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS chat_attachments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id integer NOT NULL REFERENCES chat_messages(id) ON DELETE CASCADE,
    -- Private storage:// reference; read links are signed per request for people who can read the message
    file_ref text NOT NULL,
    file_name text NOT NULL,
    content_type text NOT NULL,
    size_bytes bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_chat_attachments_message ON chat_attachments(message_id);
-- An uploaded file can be sent once
CREATE UNIQUE INDEX IF NOT EXISTS uq_chat_attachment_file ON chat_attachments(file_ref);

CREATE TABLE IF NOT EXISTS chat_group_invites (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id integer NOT NULL REFERENCES chat_conversations(id) ON DELETE CASCADE,
    invitee_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    inviter_id uuid REFERENCES users(id) ON DELETE SET NULL,
    status text NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'REVOKED', 'EXPIRED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    responded_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_chat_pending_invite ON chat_group_invites(conversation_id, invitee_id)
    WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_chat_invites_invitee ON chat_group_invites(invitee_id, status);
CREATE INDEX IF NOT EXISTS idx_chat_invites_inviter ON chat_group_invites(inviter_id, created_at);

CREATE TABLE IF NOT EXISTS chat_blocks (
    blocker_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    blocked_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (blocker_id, blocked_id),
    CHECK (blocker_id <> blocked_id)
);

CREATE INDEX IF NOT EXISTS idx_chat_blocks_blocked ON chat_blocks(blocked_id);

CREATE TABLE IF NOT EXISTS chat_settings (
    user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    direct_messages text NOT NULL CHECK (direct_messages IN ('COURSE_MEMBERS', 'STAFF_ONLY', 'NOBODY'))
);

-- Admin-imposed: the user can still read, but not send, start conversations or invite until the date
CREATE TABLE IF NOT EXISTS chat_restrictions (
    user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    until timestamptz NOT NULL,
    reason text NOT NULL,
    created_by uuid REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Chat messages can be reported like reviews, questions and answers
ALTER TABLE content_reports DROP CONSTRAINT IF EXISTS content_reports_target_type_check;
ALTER TABLE content_reports ADD CONSTRAINT content_reports_target_type_check
    CHECK (target_type IN ('REVIEW', 'QUESTION', 'ANSWER', 'CHAT_MESSAGE'));
