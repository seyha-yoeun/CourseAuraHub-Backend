-- V0072: One feedback survey per course. Learners are asked once, at half way or at completion; every survey
-- includes a 0-10 recommendation question for the course's NPS. Results reach staff only as aggregates.

CREATE TABLE IF NOT EXISTS course_surveys (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL UNIQUE REFERENCES courses(id) ON DELETE CASCADE,
    trigger text NOT NULL CHECK (trigger IN ('PERCENT_50', 'COMPLETION')),
    questions jsonb NOT NULL DEFAULT '[]'::jsonb,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS survey_responses (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id integer NOT NULL REFERENCES course_surveys(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    nps_score integer NOT NULL CHECK (nps_score BETWEEN 0 AND 10),
    answers jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (survey_id, student_id)
);

-- Who has been asked, so the prompt goes out once even if progress goes down and up again
CREATE TABLE IF NOT EXISTS survey_prompts (
    survey_id integer NOT NULL REFERENCES course_surveys(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    prompted_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (survey_id, student_id)
);
