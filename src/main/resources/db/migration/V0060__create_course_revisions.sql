-- V0060: Edits to a live instructor course wait as a revision until an admin approves them, so a published course
-- can't change price or promise without review. Approved revisions double as the course's public changelog.

CREATE TABLE IF NOT EXISTS course_revisions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    submitted_by uuid REFERENCES users(id) ON DELETE SET NULL,
    -- Field name to new value, and the same fields' values when submitted (JSON objects)
    changes text NOT NULL,
    previous text NOT NULL,
    summary text,
    status text NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'WITHDRAWN')),
    review_note text,
    reviewed_by uuid REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- At most one revision waiting per course; later edits fold into it
CREATE UNIQUE INDEX IF NOT EXISTS uq_course_revisions_pending ON course_revisions(course_id) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_course_revisions_status ON course_revisions(status, updated_at);
