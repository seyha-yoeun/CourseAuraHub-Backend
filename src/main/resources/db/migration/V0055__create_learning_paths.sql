-- V0055: Learning paths: an ordered set of courses with its own completion certificate.
-- Path certificates are permanent like course certificates, so they outlive the path itself.

CREATE TABLE IF NOT EXISTS learning_paths (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    title text NOT NULL,
    description text NOT NULL DEFAULT '',
    thumbnail text,
    status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS learning_path_courses (
    path_id integer NOT NULL REFERENCES learning_paths(id) ON DELETE CASCADE,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    position integer NOT NULL,
    PRIMARY KEY (path_id, course_id)
);

CREATE INDEX IF NOT EXISTS idx_learning_path_courses_course ON learning_path_courses(course_id);

CREATE TABLE IF NOT EXISTS learning_path_certificates (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_number text NOT NULL UNIQUE,
    path_id integer REFERENCES learning_paths(id) ON DELETE SET NULL,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    learner_name text NOT NULL,
    path_title text NOT NULL,
    issued_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (path_id, student_id)
);

CREATE INDEX IF NOT EXISTS idx_learning_path_certificates_student ON learning_path_certificates(student_id);
