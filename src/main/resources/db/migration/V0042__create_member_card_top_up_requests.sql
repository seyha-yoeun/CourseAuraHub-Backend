-- V0042: A learner asks for a top-up and an admin approves it. The money only moves on approval,
-- through the ledger, with the request as its reference.

CREATE TABLE IF NOT EXISTS member_card_top_up_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id integer NOT NULL REFERENCES member_cards(id),
    amount numeric(12, 2) NOT NULL CHECK (amount > 0),
    note text,
    receipt_url text,
    receipt_name text,
    status text NOT NULL,
    review_note text,
    reviewed_by uuid REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One request waiting per card
CREATE UNIQUE INDEX IF NOT EXISTS uq_member_card_top_up_pending
    ON member_card_top_up_requests (card_id) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_member_card_top_up_status
    ON member_card_top_up_requests (status, created_at DESC);
