-- V0076: All-access subscriptions. A subscriber enrolls in any published course through the subscription; those
-- enrollments are free (no revenue or spending) and are removed when the subscription ends. Each period is a
-- subscription payment with a SUB- number, paid by member card or through the payment provider.

CREATE TABLE IF NOT EXISTS subscription_plans (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    description text,
    price numeric(10, 2) NOT NULL CHECK (price > 0),
    billing_interval text NOT NULL CHECK (billing_interval IN ('MONTH', 'YEAR')),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS subscriptions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    plan_id integer NOT NULL REFERENCES subscription_plans(id),
    status text NOT NULL CHECK (status IN ('PENDING', 'ACTIVE', 'PAST_DUE', 'CANCELLED', 'EXPIRED')),
    provider text NOT NULL,
    current_period_start timestamptz,
    current_period_end timestamptz,
    cancel_at_period_end boolean NOT NULL DEFAULT false,
    cancelled_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- One live subscription per learner
CREATE UNIQUE INDEX IF NOT EXISTS uq_subscriptions_live ON subscriptions(student_id)
    WHERE status IN ('PENDING', 'ACTIVE', 'PAST_DUE');
CREATE INDEX IF NOT EXISTS idx_subscriptions_due ON subscriptions(status, current_period_end);

CREATE TABLE IF NOT EXISTS subscription_payments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_number text NOT NULL UNIQUE,
    subscription_id integer NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    amount numeric(10, 2) NOT NULL,
    currency text NOT NULL,
    status text NOT NULL CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'CANCELLED')),
    period_start timestamptz NOT NULL,
    period_end timestamptz NOT NULL,
    provider text NOT NULL,
    provider_reference text,
    checkout_url text,
    created_at timestamptz NOT NULL DEFAULT now(),
    paid_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_subscription_payments_subscription ON subscription_payments(subscription_id, created_at DESC);

-- Which enrollments came from a subscription, so ending it removes exactly those
CREATE TABLE IF NOT EXISTS subscription_enrollments (
    subscription_id integer NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (student_id, course_id)
);
