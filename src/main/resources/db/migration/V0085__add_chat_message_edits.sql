-- V0085: Editing sent messages. The sender may change a message for a while after sending (app.chat.edit-window).
-- Each earlier text is kept, so a moderator reviewing a report sees what the message said before it was edited.

ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS edited_at timestamptz;

CREATE TABLE IF NOT EXISTS chat_message_edits (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id integer NOT NULL REFERENCES chat_messages(id) ON DELETE CASCADE,
    -- The text before this edit; null when the message had only files
    body text,
    edited_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_chat_message_edits_message ON chat_message_edits(message_id, id);
