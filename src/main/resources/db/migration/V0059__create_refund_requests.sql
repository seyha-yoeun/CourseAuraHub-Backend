-- V0059: Learners ask for refunds in the app. Requests inside the policy are approved automatically; the rest wait
-- for an admin. A request moves no money by itself: approval refunds the order through the normal refund path.

CREATE TABLE IF NOT EXISTS refund_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    reason text NOT NULL,
    status text NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    auto_approved boolean NOT NULL DEFAULT false,
    progress_percent integer NOT NULL DEFAULT 0,
    decision_note text,
    reviewed_by uuid REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One open request per order; a decided one stays as history
CREATE UNIQUE INDEX IF NOT EXISTS uq_refund_requests_open ON refund_requests(order_id) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_refund_requests_status ON refund_requests(status, created_at);
