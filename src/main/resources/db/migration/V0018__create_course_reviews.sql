-- V0018: Learner course reviews and ratings.

CREATE TABLE IF NOT EXISTS course_reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (course_id, student_id)
);

CREATE INDEX IF NOT EXISTS idx_course_reviews_course_created ON course_reviews(course_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_course_reviews_student_id ON course_reviews(student_id);
