-- V0011: Add generated identity support for domain tables and user profile fields.

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS bio TEXT,
    ADD COLUMN IF NOT EXISTS website VARCHAR(500),
    ADD COLUMN IF NOT EXISTS twitter VARCHAR(100);

-- Hibernate's @OrderColumn uses an integer order column.
ALTER TABLE course_tags
    ALTER COLUMN tag_order TYPE integer;

DO $$
DECLARE
    sequence_name TEXT;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_name = 'courses' AND column_name = 'id' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE courses ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    sequence_name := pg_get_serial_sequence('courses', 'id');
    IF sequence_name IS NOT NULL THEN
        PERFORM setval(
            sequence_name,
            COALESCE((SELECT MAX(id) FROM courses), 0) + 1,
            false
        );
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_name = 'students' AND column_name = 'id' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE students ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    sequence_name := pg_get_serial_sequence('students', 'id');
    IF sequence_name IS NOT NULL THEN
        PERFORM setval(
            sequence_name,
            COALESCE((SELECT MAX(id) FROM students), 0) + 1,
            false
        );
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_name = 'enrollments' AND column_name = 'id' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE enrollments ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    sequence_name := pg_get_serial_sequence('enrollments', 'id');
    IF sequence_name IS NOT NULL THEN
        PERFORM setval(
            sequence_name,
            COALESCE((SELECT MAX(id) FROM enrollments), 0) + 1,
            false
        );
    END IF;
END $$;
