-- V0034: A cart, and groups that let one payment cover several orders. Each course keeps its own order,
-- so refunds, coupons and enrollment still work per course.

CREATE TABLE IF NOT EXISTS cart_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    added_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (student_id, course_id)
);

CREATE TABLE IF NOT EXISTS order_groups (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_number text NOT NULL UNIQUE,
    amount numeric(12, 2) NOT NULL DEFAULT 0,
    currency text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE orders ADD COLUMN IF NOT EXISTS group_id integer REFERENCES order_groups(id);
CREATE INDEX IF NOT EXISTS idx_orders_group ON orders(group_id) WHERE group_id IS NOT NULL;
